const LANG_KEY = "pdftr:lang";
let LANG = "de";
try { LANG = localStorage.getItem(LANG_KEY) || "de"; } catch (_) { /* storage blocked */ }
if (!I18N[LANG]) LANG = "de";

/** Format of the open document ("PDF", "EPUB", "FB2", "DOCX", …), for {fmt} in the texts. */
let DOC_FMT = "PDF";

/** Translate a key, filling {placeholders} from vars. */
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  vars = { fmt: DOC_FMT, ...vars };
  s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}

function setDocFormat(fmt) {
  if (fmt === DOC_FMT) return;
  DOC_FMT = fmt;
  applyI18n();
}

/** Apply the current language to all static elements under root. */
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.querySelectorAll(".lang-switch button").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === LANG);
    b.setAttribute("aria-pressed", String(b.dataset.lang === LANG));
  });
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch (_) { /* storage blocked */ }
  applyI18n();
  document.dispatchEvent(new CustomEvent("languagechange"));
}

